import math

# Raiz quadrada
raiz = math.sqrt(16)
print(raiz)  # Saída: 4.0

# Valor de Pi
pi = math.pi
print(pi)  # Saída: 3.141592653589793

# Cálculo de seno
seno = math.sin(math.radians(30))  # Converte graus em radianos
print(seno)  # Saída: 0.5

# Fatorial
fatorial = math.factorial(5)
print(fatorial)  # Saída: 120

divisao_inteira = 10 // 3
print(divisao_inteira)  # Saída: 3

resto = 10 % 3
print(resto)  # Saída: 1

potencia = 2 ** 3
print(potencia)  # Saída: 8

